CREATE TABLE withdrawal_transfer (
 id VARCHAR(64) PRIMARY KEY, withdrawal_id VARCHAR(64) NOT NULL UNIQUE,
 status VARCHAR(30) NOT NULL, channel_reference VARCHAR(128) UNIQUE, reason VARCHAR(500),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(withdrawal_id) REFERENCES withdrawal_request(id)
) ENGINE=InnoDB;
