export function interventionLabel(code: string) {
  if (code === 'REFUND_CHANNEL_UNCONFIGURED') return '退款渠道未配置，需线下核实'
  if (code === 'REFUND_LIMIT_REACHED') return '合并支付单退款次数达到微信侧限制'
  return stateLabel(code)
}

export function stateLabel(value: unknown) {
  if (value == null || value === '') return '—'
  const code = String(value)
  return Object.hasOwn(labels, code) ? labels[code] : code
}
